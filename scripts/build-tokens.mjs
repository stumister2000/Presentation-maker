// Generates src/styles/tokens.css and src/lib/theme-tokens.json from
// replica/design/tokens.json. Run after any token change: npm run tokens
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const t = JSON.parse(readFileSync("replica/design/tokens.json", "utf8"));
const app = Object.entries(t.color).filter(([k]) => !k.startsWith("theme-"));

const lines = [];
lines.push("/* Generated by scripts/build-tokens.mjs from replica/design/tokens.json. Do not edit. */");
lines.push("@theme {");
for (const [k, v] of app) lines.push(`  --color-${k}: ${v};`);
for (const [k, v] of Object.entries(t.font)) lines.push(`  --font-${k}: ${v};`);
for (const [k, v] of Object.entries(t.radius)) lines.push(`  --radius-${k}: ${v}px;`);
for (const [k, v] of Object.entries(t.shadow)) lines.push(`  --shadow-${k}: ${v};`);
for (const [k, v] of Object.entries(t.type)) {
  lines.push(`  --text-${k}: ${v.size / 16}rem;`);
  lines.push(`  --text-${k}--line-height: ${v.line / v.size};`);
}
lines.push(`  --ease-snappy: ${t.motion.ease};`);
lines.push("}");
lines.push(":root {");
for (const [k, v] of Object.entries(t.layout)) lines.push(`  --layout-${k}: ${v}px;`);
lines.push(`  --motion-fast: ${t.motion.fast};`);
lines.push(`  --motion-base: ${t.motion.base};`);
lines.push("}");

mkdirSync("src/styles", { recursive: true });
writeFileSync("src/styles/tokens.css", lines.join("\n") + "\n");

const themes = {};
for (const [k, v] of Object.entries(t.color)) {
  const m = k.match(/^theme-([a-z]+)-([a-z]+)$/);
  if (!m) continue;
  (themes[m[1]] ??= {})[m[2]] = v;
}
writeFileSync("src/lib/theme-tokens.json", JSON.stringify(themes, null, 2) + "\n");
console.log(`tokens: ${app.length} app colours, ${Object.keys(themes).length} deck themes`);
